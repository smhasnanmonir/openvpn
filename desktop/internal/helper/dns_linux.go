//go:build linux

package helper

import (
	"errors"
	"fmt"
	"os"
	"strings"
)

var resolvBackupPath = StateDir + "/resolv.conf.bak"

func applyDNS(dev string, servers, domains []string, full bool) error {
	if p, err := findTrusted("resolvectl"); err == nil {
		if _, statErr := os.Stat("/run/systemd/resolve"); statErr == nil {
			args := append([]string{"dns", dev}, servers...)
			if err := runTrusted(p, args...); err != nil {
				return err
			}
			switch {
			case full:
				if err := runTrusted(p, "domain", dev, "~."); err != nil {
					return err
				}
			case len(domains) > 0:
				dargs := append([]string{"domain", dev}, domains...)
				if err := runTrusted(p, dargs...); err != nil {
					return err
				}
			}
			return nil
		}
	}
	if p, err := findTrusted("resolvconf"); err == nil {
		content := resolvContent(servers, domains)
		if err := runTrustedStdin(content, p, "-a", dev+".openvpn-desktop"); err == nil {
			return nil
		}
	}
	return writeResolvConf(servers, domains)
}

func revertDNS(dev string) {
	if p, err := findTrusted("resolvectl"); err == nil {
		_ = runTrusted(p, "revert", dev)
	}
	if p, err := findTrusted("resolvconf"); err == nil {
		_ = runTrusted(p, "-d", dev+".openvpn-desktop")
	}
	_ = restoreResolvBackup()
}

func resolvContent(servers, domains []string) string {
	var b strings.Builder
	b.WriteString("# Generated by OpenVPN Desktop\n")
	for _, s := range servers {
		b.WriteString("nameserver " + s + "\n")
	}
	for _, d := range domains {
		b.WriteString("search " + d + "\n")
	}
	return b.String()
}

func writeResolvConf(servers, domains []string) error {
	const path = "/etc/resolv.conf"
	st, err := os.Lstat(path)
	if err != nil {
		return err
	}
	if st.Mode()&os.ModeSymlink != 0 {
		return errors.New("/etc/resolv.conf is a symlink (managed by systemd-resolved or resolvconf); no safe direct fallback is available")
	}
	if _, err := os.Stat(resolvBackupPath); errors.Is(err, os.ErrNotExist) {
		original, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}
		if err := writeFile(resolvBackupPath, original, 0o600); err != nil {
			return err
		}
	}
	return os.WriteFile(path, []byte(resolvContent(servers, domains)), st.Mode().Perm())
}

func restoreResolvBackup() error {
	data, err := os.ReadFile(resolvBackupPath)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		return err
	}
	const path = "/etc/resolv.conf"
	st, err := os.Lstat(path)
	if err == nil && st.Mode()&os.ModeSymlink != 0 {
		_ = os.Remove(resolvBackupPath)
		return nil
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return err
	}
	return os.Remove(resolvBackupPath)
}

